export function applyTraditionalChineseEditorialReview(catalog) {
  return applyEditorialReview(catalog, ZH_TW_EDITORIAL_PROFILES, CATEGORY_COPY, {
    label: 'Traditional Chinese',
    characteristics: (record, characteristic, categoryCopy) => [
      characteristic,
      `${record.name}${categoryCopy.structure}`,
      `${record.name}在內容、控制項與響應式狀態中維持一致的視覺語法。`,
      `${record.name}明確記錄間距與強調規則，確保構圖可以重現。`
    ],
    pros: (record, fit, categoryCopy) => [
      fit,
      `${record.name}的優勢在於，${categoryCopy.benefit}`,
      `${record.name}保留資訊層次後，可以擴充至更廣泛的製作環境。`
    ],
    cons: (record, caution) => [
      caution,
      `${record.name}發布前還需檢查窄螢幕、長文案與減少動態效果的狀態。`
    ],
    palette: (record, color, index, categoryCopy) => {
      const name = categoryCopy.paletteNames[index];
      return {
        ...color,
        name,
        usage: `${name}用於在${record.name}中${categoryCopy.paletteRoles[index]}。`
      };
    }
  });
}
