export function applySimplifiedChineseEditorialReview(catalog) {
  return applyEditorialReview(catalog, ZH_CN_EDITORIAL_PROFILES, CATEGORY_COPY, {
    label: 'Simplified Chinese',
    characteristics: (record, characteristic, categoryCopy) => [
      characteristic,
      `${record.name}${categoryCopy.structure}`,
      `${record.name}在内容、控件与响应式状态中保持一致的视觉语法。`,
      `${record.name}明确记录间距与强调规则，确保构图可以复现。`
    ],
    pros: (record, fit, categoryCopy) => [
      fit,
      `${record.name}的优势在于，${categoryCopy.benefit}`,
      `${record.name}在保留信息层级后可以扩展到更广泛的制作环境。`
    ],
    cons: (record, caution) => [
      caution,
      `${record.name}发布前还需检查窄屏、长文案与减少动态效果的状态。`
    ],
    palette: (record, color, index, categoryCopy) => {
      const name = categoryCopy.paletteNames[index];
      return {
        ...color,
        name,
        usage: `${name}用于在${record.name}中${categoryCopy.paletteRoles[index]}。`
      };
    }
  });
}
